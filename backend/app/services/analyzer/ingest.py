"""Stage 1: workspace preparation, hygiene gates, content hashing and the Merkle root.

Sources: a shallow git clone (GitHub, Bitbucket, any Git URL), an uploaded .zip / .tar.gz archive, or a local folder.
The walk applies exclusion gates before reading any file (build outputs, dependencies, caches, binaries, lockfiles,
minified bundles, .gitignore rules) and hashes every kept file with SHA-256.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import stat
import tarfile
import zipfile
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

import pathspec

from app import config
from app.errors import AppError
from app.services.analyzer import languages

MAX_ARCHIVE_RATIO = 200  # decompression-bomb guard: uncompressed / compressed
MAX_ARCHIVE_ENTRIES = 200_000
GENERATED_NAME = re.compile(r"(\.gen\.|\.generated\.|_pb2(_grpc)?\.py$|\.pb\.go$|\.pb\.(cc|h)$|\.g\.dart$|\.freezed\.dart$|\.designer\.cs$|_generated\.)", re.I)
GENERATED_MARKERS = ("code generated", "do not edit", "@generated", "auto-generated", "autogenerated", "<auto-generated")


@dataclass
class FileEntry:
    path: str  # repository-relative, POSIX separators
    size: int
    sha256: str
    language: str
    category: str  # code, markup, style, config, doc, data, script, lockfile, binary, other
    text: str | None = None
    generated: bool = False
    skipped_reason: str = ""


@dataclass
class Workspace:
    root: Path
    files: list[FileEntry] = field(default_factory=list)
    skipped: dict[str, int] = field(default_factory=dict)
    merkle_root: str = ""
    dir_hashes: dict[str, str] = field(default_factory=dict)

    @property
    def text_files(self) -> list[FileEntry]:
        return [item for item in self.files if item.text is not None]


# --- archives -----------------------------------------------------------------------------------------------------


def _safe_target(base: Path, name: str) -> Path:
    cleaned = name.replace("\\", "/").lstrip("/")
    target = (base / cleaned).resolve()
    if base.resolve() not in target.parents and target != base.resolve():
        raise AppError(400, f"The archive contains an unsafe path: {name[:200]}")  # Zip-Slip
    return target


def extract_archive(archive: Path, target: Path) -> Path:
    """Extract .zip / .tar.gz / .tgz safely and return the folder that holds the repository."""
    target.mkdir(parents=True, exist_ok=True)
    compressed = max(archive.stat().st_size, 1)
    total = 0
    name = archive.name.lower()
    if zipfile.is_zipfile(archive):
        with zipfile.ZipFile(archive) as bundle:
            members = bundle.infolist()
            if len(members) > MAX_ARCHIVE_ENTRIES:
                raise AppError(400, "The archive has too many entries")
            for member in members:
                total += member.file_size
                if total > compressed * MAX_ARCHIVE_RATIO and total > 50_000_000:
                    raise AppError(400, "The archive expands too much (possible decompression bomb)")
                destination = _safe_target(target, member.filename)
                if member.is_dir():
                    destination.mkdir(parents=True, exist_ok=True)
                    continue
                mode = (member.external_attr >> 16) & 0o170000
                if mode == stat.S_IFLNK:
                    continue  # never follow links out of the workspace
                destination.parent.mkdir(parents=True, exist_ok=True)
                with bundle.open(member) as source, open(destination, "wb") as sink:
                    shutil.copyfileobj(source, sink)
    elif name.endswith((".tar.gz", ".tgz", ".tar")) or tarfile.is_tarfile(archive):
        with tarfile.open(archive) as bundle:
            members = bundle.getmembers()
            if len(members) > MAX_ARCHIVE_ENTRIES:
                raise AppError(400, "The archive has too many entries")
            for member in members:
                if member.issym() or member.islnk() or member.isdev():
                    continue
                total += member.size
                if total > compressed * MAX_ARCHIVE_RATIO and total > 50_000_000:
                    raise AppError(400, "The archive expands too much (possible decompression bomb)")
                destination = _safe_target(target, member.name)
                if member.isdir():
                    destination.mkdir(parents=True, exist_ok=True)
                    continue
                source = bundle.extractfile(member)
                if source is None:
                    continue
                destination.parent.mkdir(parents=True, exist_ok=True)
                with source, open(destination, "wb") as sink:
                    shutil.copyfileobj(source, sink)
    else:
        raise AppError(400, "Upload a .zip, .tar.gz or .tgz archive")
    # A single top-level folder (GitHub "Download ZIP" style) becomes the root.
    entries = [entry for entry in target.iterdir() if entry.name not in ("__MACOSX", ".DS_Store")]
    if len(entries) == 1 and entries[0].is_dir():
        return entries[0]
    return target


def check_local_path(raw: str) -> Path:
    if not config.allow_local_paths():
        raise AppError(403, "Local folder analysis is disabled. Set ALLOW_LOCAL_PATHS=true on the server.")
    path = Path(raw).expanduser().resolve()
    if not path.is_dir():
        raise AppError(400, "The folder does not exist on the server")
    roots = [Path(item).expanduser().resolve() for item in config.local_path_roots()]
    if roots and not any(path == root or root in path.parents for root in roots):
        raise AppError(403, "The folder is outside LOCAL_PATH_ROOTS")
    return path


# --- walk ---------------------------------------------------------------------------------------------------------


def _ignore_spec(directory: Path) -> pathspec.PathSpec | None:
    lines: list[str] = []
    for name in (".gitignore", ".cursorignore", ".codeanalyzerignore"):
        candidate = directory / name
        if candidate.is_file():
            try:
                lines += candidate.read_text(encoding="utf-8", errors="ignore").splitlines()
            except OSError:
                continue
    if not lines:
        return None
    return pathspec.GitIgnoreSpec.from_lines(lines)


def _is_binary(sample: bytes) -> bool:
    if b"\x00" in sample:
        return True
    if not sample:
        return False
    text_chars = bytes(range(32, 127)) + b"\n\r\t\f\b"
    nontext = sample.translate(None, text_chars)
    # UTF-8 text has many high bytes; only call it binary when decoding fails as well.
    if len(nontext) / len(sample) > 0.30:
        try:
            sample.decode("utf-8")
        except UnicodeDecodeError:
            return True
    return False


def _decode(raw: bytes) -> str:
    for encoding in ("utf-8", "utf-8-sig"):
        try:
            return raw.decode(encoding)
        except UnicodeDecodeError:
            continue
    return raw.decode("latin-1", errors="replace")


def walk(root: Path, cancelled=lambda: False, progress=lambda done: None) -> Workspace:
    workspace = Workspace(root=root)
    skipped: dict[str, int] = {}
    max_bytes = config.max_file_bytes()
    max_files = config.max_files()
    specs: list[tuple[str, pathspec.PathSpec]] = []

    def skip(reason: str) -> None:
        skipped[reason] = skipped.get(reason, 0) + 1

    for current, dirnames, filenames in os.walk(root, followlinks=False):
        if cancelled():
            raise AppError(409, "Analysis cancelled")
        current_path = Path(current)
        rel_dir = current_path.relative_to(root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        # ignore files apply to their own folder and below
        specs = [(base, spec) for base, spec in specs if not base or rel_dir == base or rel_dir.startswith(base + "/")]
        spec = _ignore_spec(current_path)
        if spec is not None:
            specs.append((rel_dir, spec))

        def ignored(rel: str, is_dir: bool) -> bool:
            for base, item in specs:
                local = rel[len(base) + 1 :] if base else rel
                if item.match_file(local + ("/" if is_dir else "")):
                    return True
            return False

        has_dotnet = any(name.endswith((".csproj", ".vbproj", ".fsproj")) for name in filenames)
        kept_dirs = []
        for name in sorted(dirnames):
            rel = f"{rel_dir}/{name}" if rel_dir else name
            if name in languages.EXCLUDED_DIRS or (has_dotnet and name in languages.DOTNET_OUTPUT_DIRS):
                skip(f"excluded folder ({name}/)")
                continue
            if name.startswith(".") and name not in (".github", ".gitlab", ".circleci", ".devcontainer", ".husky"):
                skip("hidden folder")
                continue
            if (current_path / name).is_symlink():
                skip("symbolic link")
                continue
            if ignored(rel, True):
                skip(".gitignore rule")
                continue
            kept_dirs.append(name)
        dirnames[:] = kept_dirs

        for name in sorted(filenames):
            rel = f"{rel_dir}/{name}" if rel_dir else name
            full = current_path / name
            if full.is_symlink():
                skip("symbolic link")
                continue
            if name in (".DS_Store", "Thumbs.db"):
                continue
            if ignored(rel, False):
                skip(".gitignore rule")
                continue
            try:
                size = full.stat().st_size
            except OSError:
                skip("unreadable")
                continue
            lowered = name.lower()
            suffix = PurePosixPath(lowered).suffix
            language, category = languages.classify_path(rel)
            if lowered in languages.LOCKFILES:
                workspace.files.append(FileEntry(rel, size, _hash_file(full), language or "Lockfile", "lockfile", None, False, "lockfile"))
                continue
            if suffix in languages.BINARY_EXTENSIONS:
                workspace.files.append(FileEntry(rel, size, _hash_file(full), "Binary", "binary", None, False, "binary"))
                skip("binary asset")
                continue
            if languages.is_minified(name):
                skip("minified bundle")
                continue
            if len(workspace.files) >= max_files:
                skip("file limit reached")
                continue
            if size > max_bytes:
                workspace.files.append(FileEntry(rel, size, _hash_file(full), language, category, None, False, "too large"))
                skip("larger than ANALYSIS_MAX_FILE_BYTES")
                continue
            try:
                raw = full.read_bytes()
            except OSError:
                skip("unreadable")
                continue
            digest = hashlib.sha256(raw).hexdigest()
            if _is_binary(raw[:8192]):
                workspace.files.append(FileEntry(rel, size, digest, "Binary", "binary", None, False, "binary"))
                skip("binary content")
                continue
            text = _decode(raw)
            head = text[:600].lower()
            generated = (
                "/generated/" in f"/{rel.lower()}"
                or GENERATED_NAME.search(name) is not None
                or any(marker in head for marker in GENERATED_MARKERS)
            )
            if category == "other" and not language:
                category = "other"
            workspace.files.append(FileEntry(rel, size, digest, language or "Other", category, text, generated))
        progress(len(workspace.files))
    workspace.skipped = skipped
    workspace.merkle_root, workspace.dir_hashes = merkle(workspace.files)
    return workspace


def _hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    try:
        with open(path, "rb") as handle:
            for block in iter(lambda: handle.read(1 << 20), b""):
                digest.update(block)
    except OSError:
        return ""
    return digest.hexdigest()


def merkle(files: list[FileEntry]) -> tuple[str, dict[str, str]]:
    """Directory hashes from their children's hashes up to one root hash (content-addressed, order-independent)."""
    children: dict[str, list[tuple[str, str]]] = {}
    for item in files:
        parent = str(PurePosixPath(item.path).parent)
        parent = "" if parent == "." else parent
        children.setdefault(parent, []).append((PurePosixPath(item.path).name, item.sha256))
        # make sure every ancestor exists
        while parent:
            grand = str(PurePosixPath(parent).parent)
            grand = "" if grand == "." else grand
            children.setdefault(grand, [])
            parent = grand
    hashes: dict[str, str] = {}
    for directory in sorted(children, key=lambda value: value.count("/") + (1 if value else 0), reverse=True):
        entries = children[directory]
        payload = "\n".join(f"{name}:{digest}" for name, digest in sorted(entries))
        hashes[directory] = hashlib.sha256(payload.encode()).hexdigest()
        if directory:
            parent = str(PurePosixPath(directory).parent)
            parent = "" if parent == "." else parent
            children[parent].append((PurePosixPath(directory).name + "/", hashes[directory]))
    return hashes.get("", hashlib.sha256(b"").hexdigest()), hashes


def cleanup(path: Path | None) -> None:
    if path and path.exists():
        shutil.rmtree(path, ignore_errors=True)
